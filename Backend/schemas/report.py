from enum import Enum
from typing import List, Optional, Dict, Any, Union
from pydantic import BaseModel, Field, field_validator, model_validator


class HiringDecision(str, Enum):
    STRONG_HIRE = "Strong Hire"
    HIRE = "Hire"
    WEAK_HIRE = "Weak Hire"
    NO_HIRE = "No Hire"


class CategoryScores(BaseModel):
    technical_correctness: int = Field(default=80, ge=0, le=100)
    system_design_scalability: int = Field(default=80, ge=0, le=100)
    problem_solving_adaptability: int = Field(default=80, ge=0, le=100)
    communication_clarity: int = Field(default=80, ge=0, le=100)

    @field_validator("technical_correctness", "system_design_scalability", "problem_solving_adaptability", "communication_clarity", mode="before")
    @classmethod
    def clamp_score(cls, v: Any) -> int:
        try:
            val = int(v)
            return max(0, min(100, val))
        except (ValueError, TypeError):
            return 80


class FollowupReportItem(BaseModel):
    """
    Pydantic schema for validating each follow-up question before saving to session history.
    """
    followup_number: int = Field(default=1, ge=1, le=2)
    que: str = Field(..., description="Follow-up question asked by interviewer")
    ans: str = Field(default="No answer recorded.", description="Candidate's answer to follow-up")
    score: int = Field(default=75, ge=0, le=100)
    improvement: List[str] = Field(default_factory=list, description="Follow-up specific improvements")
    strengths: List[str] = Field(default_factory=list, description="Follow-up specific strengths")

    @model_validator(mode="before")
    @classmethod
    def normalize_followup_fields(cls, values: Any) -> Any:
        if not isinstance(values, dict):
            return values

        # Normalize question text
        que = values.get("que") or values.get("question") or values.get("question_text") or values.get("followup_text") or "Follow-up question"
        values["que"] = str(que).strip()

        # Normalize answer text
        ans = values.get("ans") or values.get("answer") or values.get("answer_text") or values.get("transcript") or "No answer recorded."
        values["ans"] = str(ans).strip() or "No answer recorded."

        # Normalize improvements & strengths
        raw_imp = values.get("improvement") or values.get("areas_for_improvement") or []
        if isinstance(raw_imp, str):
            raw_imp = [raw_imp] if raw_imp.strip() else []
        values["improvement"] = [str(i).strip() for i in raw_imp if str(i).strip()]

        raw_str = values.get("strengths") or []
        if isinstance(raw_str, str):
            raw_str = [raw_str] if raw_str.strip() else []
        values["strengths"] = [str(s).strip() for s in raw_str if str(s).strip()]

        # Clamp followup number between 1 and 2
        fnum = values.get("followup_number", 1)
        try:
            values["followupup_number"] = max(1, min(2, int(fnum)))
        except (ValueError, TypeError):
            values["followup_number"] = 1

        # Clamp score between 0 and 100
        score = values.get("score", 75)
        try:
            values["score"] = max(0, min(100, int(score)))
        except (ValueError, TypeError):
            values["score"] = 75

        return values


class QuestionReportItem(BaseModel):
    """
    Pydantic schema for validating each main question and its answers/evaluations
    before saving into sessions.
    """
    question_number: int = Field(default=1, ge=1)
    topic: str = Field(default="Core Competency", description="Topic of this question")
    que: str = Field(..., description="Question text from session history")
    ans: str = Field(default="No answer recorded.", description="Candidate response from session history")
    score: int = Field(default=75, ge=0, le=100)
    improvement: List[str] = Field(default_factory=list, description="Improvements generated by LLM")
    strengths: List[str] = Field(default_factory=list, description="Strengths identified by LLM")
    feedback: Optional[str] = Field(default=None, description="Spoken feedback from evaluator")
    follow_ups: List[FollowupReportItem] = Field(default_factory=list, description="List of nested follow-up evaluations (max 2)")

    @model_validator(mode="before")
    @classmethod
    def normalize_question_fields(cls, values: Any) -> Any:
        if not isinstance(values, dict):
            return values

        # 1. Normalize Topic
        topic = values.get("topic") or values.get("round_name") or values.get("category") or values.get("round") or "Technical Assessment"
        values["topic"] = str(topic).strip()

        # 2. Normalize Question Text (que)
        que = values.get("que") or values.get("question") or values.get("question_text") or values.get("title") or values.get("prompt") or "Interview Question"
        values["que"] = str(que).strip()

        # 3. Normalize Candidate Answer (ans)
        ans = values.get("ans") or values.get("answer") or values.get("answer_text") or values.get("transcript") or "No answer recorded."
        values["ans"] = str(ans).strip() or "No answer recorded."

        # 4. Normalize Score
        score = values.get("score", 75)
        try:
            values["score"] = max(0, min(100, int(score)))
        except (ValueError, TypeError):
            values["score"] = 75

        # 5. Normalize Improvement List
        raw_imp = values.get("improvement") or values.get("areas_for_improvement") or []
        if isinstance(raw_imp, str):
            raw_imp = [raw_imp] if raw_imp.strip() else []
        values["improvement"] = [str(i).strip() for i in raw_imp if str(i).strip()]

        # 6. Normalize Strengths List
        raw_str = values.get("strengths") or []
        if isinstance(raw_str, str):
            raw_str = [raw_str] if raw_str.strip() else []
        values["strengths"] = [str(s).strip() for s in raw_str if str(s).strip()]

        # 7. Normalize Feedback
        if "feedback" in values and values["feedback"]:
            values["feedback"] = str(values["feedback"]).strip()

        # 8. Normalize & Cap Follow-ups (Strict constraint: maximum 2 follow-ups)
        raw_fups = values.get("follow_ups") or []
        if isinstance(raw_fups, list):
            validated_fups = []
            for idx, item in enumerate(raw_fups[:2], start=1):
                if isinstance(item, FollowupReportItem):
                    validated_fups.append(item)
                elif isinstance(item, dict):
                    item["followup_number"] = idx
                    validated_fups.append(FollowupReportItem.model_validate(item))
            values["follow_ups"] = validated_fups
        else:
            values["follow_ups"] = []

        return values


def validate_question_structure(data: Union[Dict[str, Any], QuestionReportItem]) -> QuestionReportItem:
    """
    Validates any question structure against the QuestionReportItem Pydantic schema
    before saving it into sessions.
    """
    if isinstance(data, QuestionReportItem):
        return data
    return QuestionReportItem.model_validate(data)


class ReportLLMOutput(BaseModel):
    """
    Pydantic schema used to strictly validate the raw JSON output from the Entire Report LLM evaluation.
    """
    hiring_decision: str = Field(default="Hire")
    overall_score: int = Field(default=80, ge=0, le=100)
    summary: str = Field(default="Candidate showed solid comprehension and relevant background.", min_length=10)
    category_scores: CategoryScores = Field(default_factory=CategoryScores)
    key_strengths: List[str] = Field(default_factory=list)
    key_improvements: List[str] = Field(default_factory=list)
    actionable_recommendations: List[str] = Field(default_factory=list)

    @field_validator("overall_score", mode="before")
    @classmethod
    def clamp_overall_score(cls, v: Any) -> int:
        try:
            val = int(v)
            return max(0, min(100, val))
        except (ValueError, TypeError):
            return 80

    @field_validator("hiring_decision", mode="before")
    @classmethod
    def normalize_decision(cls, v: Any) -> str:
        s = str(v).strip().title()
        valid = {"Strong Hire", "Hire", "Weak Hire", "No Hire"}
        return s if s in valid else "Hire"


class EntireReportEvaluation(BaseModel):
    """
    Complete schema for the finalized session report persisted to Sessions/{session_id}.json.
    Every question in this report is strictly validated by QuestionReportItem.
    """
    report_id: str
    session_id: str
    generated_at: str
    target_role: str
    seniority_level: str
    hiring_decision: str = "Hire"
    overall_score: int = Field(ge=0, le=100)
    summary: str
    category_scores: CategoryScores
    key_strengths: List[str] = Field(default_factory=list)
    key_improvements: List[str] = Field(default_factory=list)
    actionable_recommendations: List[str] = Field(default_factory=list)
    questions: List[QuestionReportItem] = Field(default_factory=list)
    saved_path: Optional[str] = None

    @field_validator("questions", mode="before")
    @classmethod
    def validate_all_questions(cls, q_list: Any) -> List[QuestionReportItem]:
        if not isinstance(q_list, list):
            return []
        validated = []
        for idx, item in enumerate(q_list, start=1):
            if isinstance(item, QuestionReportItem):
                validated.append(item)
            elif isinstance(item, dict):
                if "question_number" not in item:
                    item["question_number"] = idx
                validated.append(QuestionReportItem.model_validate(item))
        return validated
